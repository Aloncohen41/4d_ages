#!/usr/bin/env node
/*
 * Builds src/lib/growthRefs.ts: the growth reference tables the Growth page's percentiles are worked out from (L, M and S for each age).
 *
 *     node scripts/make-growth-refs.mjs
 *
 * WHO (the default): the WHO Child Growth Standards, birth to 5 years (weight, length/height, head circumference), as published by WHO in its
 * "anthro" software; then the WHO 2007 reference, 5 to 19 years (height, and weight up to 10). UK-WHO uses these same WHO standards from
 * 2 weeks to 4 years; its UK90 parts are licensed by the Child Growth Foundation and are not included.
 * CDC (the US charts): the CDC 2000 growth charts, birth to 36 months (infants) and 2 to 20 years.
 * The WHO tables, given per day, are kept per month; the CDC ones as published (every half month).
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WHO = "https://raw.githubusercontent.com/WorldHealthOrganization";
const CDC = "https://www.cdc.gov/growthcharts/data/zscore";
const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: ${r.status}`);
  return r.text();
};
const rows = (text) => text.trim().split(/\r?\n/).slice(1).map((l) => l.split(/[\t,]/).map((x) => x.trim()));
const r4 = (x) => Number(Number(x).toPrecision(6));

// WHO 0–5 years, per day → per month (a month is 30.4375 days)
async function whoDaily(file) {
  const out = { 1: [], 2: [] };
  const byDay = new Map(rows(await get(`${WHO}/anthro/master/data-raw/growthstandards/${file}.txt`)).map((r) => [`${r[0]}-${r[1]}`, r]));
  for (const sex of [1, 2]) for (let m = 0; m <= 60; m++) {
    // the exact age of that month falls between two days: interpolate, as WHO does for its monthly tables
    const day = m * 30.4375, d0 = Math.floor(day), f = day - d0;
    const a = byDay.get(`${sex}-${d0}`), b = byDay.get(`${sex}-${d0 + 1}`) ?? a;
    if (a) out[sex].push([m, ...[2, 3, 4].map((k) => r4(Number(a[k]) + f * (Number(b[k]) - Number(a[k]))))]);
  }
  return out;
}
// WHO 2007, 5–19 years, per month
async function who2007(file) {
  const out = { 1: [], 2: [] };
  for (const r of rows(await get(`${WHO}/anthroplus/master/data-raw/growthstandards/${file}.txt`))) {
    if (Number(r[1]) > 60) out[r[0]].push([Number(r[1]), r4(r[2]), r4(r[3]), r4(r[4])]);
  }
  return out;
}
// CDC 2000: Sex, Agemos, L, M, S
async function cdc(file, from = 0, to = 999) {
  const out = { 1: [], 2: [] };
  for (const r of rows(await get(`${CDC}/${file}.csv`))) {
    const age = Number(r[1]);
    if (r[0] && age >= from && age < to) out[r[0]].push([age, r4(r[2]), r4(r[3]), r4(r[4])]);
  }
  return out;
}
const join2 = (a, b) => ({ 1: [...a[1], ...b[1]], 2: [...a[2], ...b[2]] });

const tables = {
  who: {
    weight: join2(await whoDaily("weianthro"), await who2007("wfawho2007")),
    height: join2(await whoDaily("lenanthro"), await who2007("hfawho2007")),
    head: await whoDaily("hcanthro"),
  },
  cdc: {
    weight: join2(await cdc("wtageinf", 0, 24), await cdc("wtage", 24)),
    height: join2(await cdc("lenageinf", 0, 24), await cdc("statage", 24)),
    head: await cdc("hcageinf"),
  },
};

const lines = [];
for (const [src, byMeasure] of Object.entries(tables)) {
  lines.push(`  ${src}: {`);
  for (const [measure, bySex] of Object.entries(byMeasure)) {
    lines.push(`    ${measure}: {`);
    for (const sex of [1, 2]) lines.push(`      ${sex === 1 ? "boy" : "girl"}: ${JSON.stringify(bySex[sex])},`);
    lines.push(`    },`);
  }
  lines.push(`  },`);
}
const file = `// Generated by scripts/make-growth-refs.mjs — do not edit by hand. Sources and licence notes are in that script.
/** [age in months, L, M, S] rows, by chart, measurement and sex. */
export type LmsRow = [number, number, number, number];
export const GROWTH_REFS: Record<"who" | "cdc", Record<"weight" | "height" | "head", Record<"boy" | "girl", LmsRow[]>>> = {
${lines.join("\n")}
};
`;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "growthRefs.ts");
writeFileSync(out, file);
console.log(`src/lib/growthRefs.ts  ${(file.length / 1024).toFixed(0)} KB`);
